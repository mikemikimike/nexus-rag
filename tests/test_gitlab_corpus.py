def test_a_second_sync_of_an_unchanged_repository_embeds_nothing(gitlab, cache):
    index = KnowledgeIndex(Settings(), FakeModelGateway())

    first = index.sync(corpus(gitlab, cache))
    second = index.sync(corpus(gitlab, cache))

    assert (first.added, first.failed) == (5, 0)
    assert (second.added, second.replaced, second.removed, second.unchanged) == (0, 0, 0, 5)


