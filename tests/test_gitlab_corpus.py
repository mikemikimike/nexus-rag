import shutil

import pytest

from fake_gitlab import FakeGitLab
from local_rag import KnowledgeIndex, Settings
from local_rag.corpus import listing_failures
from local_rag.declaration import Declaration
from local_rag.fakes import FakeModelGateway
from local_rag.gitlab import GitLabCorpus, Repository

REPOSITORY = "platform/payments"
TOKEN = "glpat-s3cr3t-t0ken"
FILES = ("README.md", "src/ledger.py", "Makefile", "Dockerfile", "tests/test_ledger.py")


@pytest.fixture
def gitlab(tmp_path):
    gitlab = FakeGitLab(tmp_path / "remote")
    gitlab.commit(REPOSITORY, {
        "README.md": "# Payments\n\nThe ledger service posts every ZX-9000 settlement.\n",
        "src/ledger.py": "def post_entry(account, amount):\n    return account.balance + amount\n",
        "Makefile": "all:\n\tpython -m build\n",
        "Dockerfile": "FROM python:3.12\nRUN pip install ledgerlib\n",
        "tests/test_ledger.py": "def test_post_entry():\n    assert post_entry\n",
    })
    return gitlab


@pytest.fixture
def cache(tmp_path):
    return tmp_path / "mirrors"


def corpus(gitlab, cache, *repositories, token=TOKEN, **options):
    repositories = repositories or (Repository(REPOSITORY, "main"),)
    return GitLabCorpus(list(repositories), url=gitlab.url, token=token, cache=cache, **options)


def document_ids(corpus):
    return {ref.id for ref in corpus.list()}


def ids(*names):
    return {f"{REPOSITORY}@main:{name}" for name in names}


def test_each_file_is_a_document_identified_by_repository_ref_and_path(gitlab, cache):
    assert document_ids(corpus(gitlab, cache)) == ids(*FILES)


def test_a_document_has_its_blob_sha_as_version_and_the_parent_group_as_space(gitlab, cache):
    gitlab_corpus = corpus(gitlab, cache)
    document_id = f"{REPOSITORY}@main:src/ledger.py"
    blob = gitlab.git(REPOSITORY, "rev-parse", "main:src/ledger.py")

    raw = gitlab_corpus.fetch(document_id)

    assert {ref.id: ref.version for ref in gitlab_corpus.list()}[document_id] == blob
    assert (raw.id, raw.version, raw.space) == (document_id, blob, "platform")
    assert raw.title == "payments/src/ledger.py"
    assert raw.url == f"{gitlab.url}/{REPOSITORY}/-/blob/main/src/ledger.py"
    assert raw.content.startswith(b"def post_entry")


def test_a_top_level_repository_has_an_empty_space(gitlab, cache):
    gitlab.commit("tools", {"run.sh": "echo hi\n"})

    raw = corpus(gitlab, cache, Repository("tools", "main")).fetch("tools@main:run.sh")

    assert (raw.space, raw.title) == ("", "tools/run.sh")


def test_the_corpus_assigns_its_own_media_types(gitlab, cache):
    gitlab.commit(REPOSITORY, {"docs/guide.rst": "Guide\n=====\n\nHello.\n"})
    gitlab_corpus = corpus(gitlab, cache)
    types = {name: gitlab_corpus.fetch(f"{REPOSITORY}@main:{name}").media_type
             for name in ("README.md", "docs/guide.rst", "src/ledger.py", "Makefile",
                          "Dockerfile")}

    assert types["README.md"] == "text/markdown"
    assert types["docs/guide.rst"] == "text/x-rst"
    assert types["src/ledger.py"] == "text/x-python"
    assert types["Makefile"] == "text/x-makefile"
    assert types["Dockerfile"] == "text/x-dockerfile"


def test_binary_oversized_vendored_generated_minified_and_lockfile_files_are_left_out(
        gitlab, cache):
    gitlab.commit(REPOSITORY, {
        "logo.py": b"\x00\x01\x02 not text",
        "big.py": "x = 1\n" * 50_000,
        "vendor/lib/util.py": "def util(): pass\n",
        "web/node_modules/pkg/index.js": "module.exports = 1\n",
        "dist/bundle.js": "var a = 1;\n",
        "build/out.py": "x = 1\n",
        "poetry.lock": "[[package]]\nname = 'x'\n",
        "package-lock.json": "{}\n",
        "static/app.min.js": "var a=1;\n",
        "api/ledger_pb2.py": "x = 1\n",
        "api/schema.py": "# Code generated by tool. DO NOT EDIT.\nx = 1\n",
        "empty.py": "",
        "image.png": "not code",
        "src/vendor_notes.py": "def kept(): pass\n",
    })

    assert document_ids(corpus(gitlab, cache)) == ids(*FILES, "src/vendor_notes.py")


def test_a_second_sync_of_an_unchanged_repository_embeds_nothing(gitlab, cache):
    index = KnowledgeIndex(Settings(), FakeModelGateway())

    first = index.sync(corpus(gitlab, cache))
    second = index.sync(corpus(gitlab, cache))

    assert (first.added, first.failed) == (5, 0)
    assert (second.added, second.replaced, second.removed, second.unchanged) == (0, 0, 0, 5)


def test_a_changed_file_is_updated_and_a_deleted_file_removed(gitlab, cache):
    index = KnowledgeIndex(Settings(), FakeModelGateway())
    index.sync(corpus(gitlab, cache))
    gitlab.commit(REPOSITORY, {"src/ledger.py": "def post_entry(): return 2\n", "Makefile": None})

    report = index.sync(corpus(gitlab, cache))

    assert (report.replaced, report.removed, report.unchanged) == (1, 1, 3)


def test_deleting_the_cache_is_safe(gitlab, cache):
    first = document_ids(corpus(gitlab, cache))
    shutil.rmtree(cache)

    assert document_ids(corpus(gitlab, cache)) == first


def test_code_is_searchable_together_with_the_docs_end_to_end(gitlab, cache):
    index = KnowledgeIndex(Settings(), FakeModelGateway())
    index.sync(corpus(gitlab, cache, name="code"))

    found = index.search("ZX-9000 settlement")[0]

    assert found.document_id == f"code:{REPOSITORY}@main:README.md"
    assert (found.title, found.space) == ("payments/README.md", "platform")
    assert "post_entry" in index.get_document(f"code:{REPOSITORY}@main:src/ledger.py")


def test_a_repository_that_cannot_be_fetched_is_a_failure_not_an_empty_repository(
        gitlab, cache):
    index = KnowledgeIndex(Settings(), FakeModelGateway())
    index.sync(corpus(gitlab, cache))
    broken = corpus(gitlab, cache, Repository("platform/missing", "main"),
                    Repository(REPOSITORY, "main"))

    listing = broken.list()
    report = index.sync(broken)

    assert list(listing_failures(listing)) == ["platform/missing@main"]
    assert document_ids(broken) == ids(*FILES)
    assert list(report.failures) == ["platform/missing@main"]
    assert report.removed == 0


def test_a_failed_repository_keeps_its_indexed_documents(gitlab, cache):
    index = KnowledgeIndex(Settings(), FakeModelGateway())
    index.sync(corpus(gitlab, cache))

    report = index.sync(corpus(gitlab, cache, Repository(REPOSITORY, "no-such-branch")))

    assert list(report.failures) == [f"{REPOSITORY}@no-such-branch"]
    assert report.removed == 0
    assert index.get_document(f"gitlab:{REPOSITORY}@main:README.md") is not None


def test_the_token_never_appears_in_a_failure(cache):
    unreachable = GitLabCorpus([Repository(REPOSITORY, "main")], url="http://127.0.0.1:1",
                               token=TOKEN, cache=cache)

    failures = listing_failures(unreachable.list())

    assert list(failures) == [f"{REPOSITORY}@main"]
    assert TOKEN not in str(failures)


def test_the_token_is_not_stored_in_the_mirror(gitlab, cache):
    document_ids(corpus(gitlab, cache))

    stored = [path.read_bytes() for path in cache.rglob("*") if path.is_file()]

    assert stored and not any(TOKEN.encode() in content for content in stored)


def test_a_missing_git_is_a_failure(gitlab, cache):
    listing = corpus(gitlab, cache, git_bin="/nonexistent/git").list()

    assert "git not found" in listing_failures(listing)[f"{REPOSITORY}@main"]


def test_the_declaration_builds_a_gitlab_corpus_from_the_environment(gitlab, cache, tmp_path):
    file = tmp_path / "corpora.toml"
    file.write_text(f'''
[corpus.code]
kind = "gitlab"
cache = "{cache}"
[[corpus.code.repositories]]
path = "{REPOSITORY}"
refs = ["main"]
''')
    environ = {"GITLAB_URL": gitlab.url, "GITLAB_TOKEN": TOKEN}

    built = Declaration.read(file).corpus("code", environ)

    assert built.name == "code"
    assert document_ids(built) == ids(*FILES)
